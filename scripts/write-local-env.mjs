// Writes .env.development.local from the running local Supabase stack.
// Next.js loads .env.development.local only for `next dev`, and it takes
// precedence over .env.local — so dev talks to the local DB while builds and
// production keep using the hosted project's values.
//
// Usage: npm run db:env   (after `npm run db:start`)

import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let status;
try {
  status = JSON.parse(execSync("npx supabase status -o json", { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }));
} catch {
  console.error("Could not read local Supabase status. Is it running? Try `npm run db:start`.");
  process.exit(1);
}

const url = status.API_URL;
const anonKey = status.ANON_KEY ?? status.PUBLISHABLE_KEY;
if (!url || !anonKey) {
  console.error("Local Supabase status did not include API_URL / ANON_KEY:", Object.keys(status));
  process.exit(1);
}

writeFileSync(
  ".env.development.local",
  [
    "# Generated by `npm run db:env` — local Supabase stack (dev only).",
    "# Delete this file to point `npm run dev` back at the hosted project.",
    `NEXT_PUBLIC_SUPABASE_URL=${url}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
    "",
  ].join("\n")
);
console.log(`Wrote .env.development.local → ${url}`);
