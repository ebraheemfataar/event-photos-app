// Writes .env.development.local from the running local Supabase stack.
// Next.js loads .env.development.local only for `next dev`, and it takes
// precedence over .env.local — so dev talks to the local DB while builds and
// production keep using the hosted project's values.
//
// Usage: npm run db:env   (after `npm run db:start`)

import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

let status;
try {
  status = JSON.parse(execSync("npx supabase status -o json", { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }));
} catch {
  console.error("Could not read local Supabase status. Is it running? Try `npm run db:start`.");
  process.exit(1);
}

const url = status.API_URL;
const anonKey = status.ANON_KEY ?? status.PUBLISHABLE_KEY;
const serviceKey = status.SERVICE_ROLE_KEY ?? status.SECRET_KEY;
if (!url || !anonKey || !serviceKey) {
  console.error("Local Supabase status did not include API_URL / ANON_KEY / SERVICE_ROLE_KEY:", Object.keys(status));
  process.exit(1);
}

// Keep your own PayFast sandbox settings across re-runs.
const kept = existsSync(".env.development.local")
  ? readFileSync(".env.development.local", "utf8")
      .split(/\r?\n/)
      .filter((l) => /^PAYFAST_(MERCHANT_ID|MERCHANT_KEY|PASSPHRASE|SANDBOX)=/.test(l))
  : [];

writeFileSync(
  ".env.development.local",
  [
    "# Generated by `npm run db:env` — local Supabase stack (dev only).",
    "# Delete this file to point `npm run dev` back at the hosted project.",
    `NEXT_PUBLIC_SUPABASE_URL=${url}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
    "# Server-only (lib/supabase/server.ts). The local stack's built-in key, not a real secret.",
    `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
    "# Lets you (and tests) call /api/cron/expire locally. Not a real secret.",
    "CRON_SECRET=local-cron-secret",
    "# Signs you in to http://localhost:3000/admin locally. Not a real secret.",
    "ADMIN_PASSWORD=local-admin-password",
    "# PayFast: put YOUR sandbox account here (sandbox.payfast.co.za → Account",
    "# Information); these lines are kept when you re-run npm run db:env.",
    "# PayFast's old shared test merchant (10000100) no longer accepts payments.",
    ...(kept.length ? kept : ["PAYFAST_MERCHANT_ID=", "PAYFAST_MERCHANT_KEY=", "PAYFAST_PASSPHRASE=", "PAYFAST_SANDBOX=true"]),
    "# The ITN handler skips the call back to PayFast here only, because PayFast",
    "# can't reach localhost (ignored in production).",
    "PAYFAST_SKIP_REMOTE_CHECKS=true",
    "# Enforce the guest cap locally, like after launch (the seed album is exempt).",
    "PLAN_LIMITS_ENFORCED=true",
    "",
  ].join("\n")
);
console.log(`Wrote .env.development.local → ${url}`);
